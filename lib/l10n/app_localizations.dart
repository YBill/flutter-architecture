  /// In en, this message translates to:
  /// **'Start Free Reading'**
  String get startFreeReading;

  /// No description provided for @youMightLike.
  ///
  /// In en, this message translates to:
  /// **'You Might Be Like'**
  String get youMightLike;

  /// No description provided for @library.
